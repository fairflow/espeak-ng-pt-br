def complete_all_translations():
    """Complete all translations in scene JSON files."""
    scenes_dir = Path('language_materials/fr/story-scenes-json')
    
    if not scenes_dir.exists():
        print(f"❌ Directory not found: {scenes_dir}")
        return
    
    scene_files = sorted(scenes_dir.glob('scene-*.json'))
    
    total_translated = 0
    still_missing = 0
    
    for scene_file in scene_files:
        print(f"\n📄 {scene_file.name}")
        
        with open(scene_file, 'r', encoding='utf-8') as f:
            phrases = json.load(f)
        
        translated = 0
        for phrase_obj in phrases:
            french = phrase_obj.get('french', '')
            english = phrase_obj.get('english', '')
            
            if not english or english == '[TO TRANSLATE]':
                # Try exact match
                if french in COMPLETE_TRANSLATIONS:
                    phrase_obj['english'] = COMPLETE_TRANSLATIONS[french]
                    translated += 1
                else:
                    # Try without punctuation
                    base = french.rstrip('.,!?;:')
                    if base in COMPLETE_TRANSLATIONS:
                        eng = COMPLETE_TRANSLATIONS[base]
                        if french != base and french[-1] in '.,!?;:':
                            eng += french[-1]
                        phrase_obj['english'] = eng
                        translated += 1
                    else:
                        still_missing += 1
                        # Keep the placeholder
                        phrase_obj['english'] = '[TO TRANSLATE]'
        
        # Save updated file
        with open(scene_file, 'w', encoding='utf-8') as f:
            json.dump(phrases, f, ensure_ascii=False, indent=2)
        
        print(f"  ✓ Translated {translated} phrases")
        total_translated += translated
    
    print(f"\n{'='*70}")
    print(f"✅ COMPLETE! Translated {total_translated} phrases")
    if still_missing > 0:
        print(f"⚠️  {still_missing} phrases still need translation")
    else:
        print(f"🎉 ALL TRANSLATIONS COMPLETE!")
    print(f"{'='*70}")

if __name__ == '__main__':
    complete_all_translations()
